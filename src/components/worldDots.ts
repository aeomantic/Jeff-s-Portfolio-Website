export const MAP_WIDTH = 1000
export const LAT_TOP = 82
export const LAT_BOTTOM = -56
export const MAP_HEIGHT = Math.round(((LAT_TOP - LAT_BOTTOM) / 360) * MAP_WIDTH)

export function project(lon: number, lat: number): [number, number] {
  return [((lon + 180) / 360) * MAP_WIDTH, ((LAT_TOP - lat) / 360) * MAP_WIDTH]
}

function inside(lon: number, lat: number, ring: Ring): boolean {
  let hit = false
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i]
    const [xj, yj] = ring[j]
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit
  }
  return hit
}

let cached: string | null = null

/** One SVG path `d` string with a zero-length segment per land dot. */
export function worldDotsPath(step = 2.4): string {
  if (cached) return cached
  const parts: string[] = []
  for (let lat = LAT_TOP - step / 2; lat > LAT_BOTTOM; lat -= step) {
    // Offset alternate rows slightly for a woven, less mechanical texture.
    const offset = Math.round((LAT_TOP - lat) / step) % 2 ? step / 2 : 0
    for (let lon = -180 + step / 2 + offset; lon < 180; lon += step) {
      if (LAND.some((ring) => inside(lon, lat, ring))) {
        const [x, y] = project(lon, lat)
        parts.push(`M${x.toFixed(1)} ${y.toFixed(1)}h0`)
      }
    }
  }
  cached = parts.join('')
  return cached
}
